int create_server_socket(int port) {
    // Creating a server socket
    // AF_INET for IPv4 (AF_INET6 for IPv6 or dual-stack sockets)
    // SOCK_STREAM for TCP
    // protocol set to 0 for auto
    int server_fd = socket(AF_INET, SOCK_STREAM, 0);

    if (server_fd == -1) {
        throw std::runtime_error("Failed to create server socket");
    }

    // Set socket options
    // bind() function
    int val = 1;
    // Set SO_REUSEADDR to value 1
    // if not, server program cannot bind to the same IP:Port it was using after
    // restart
    if (setsockopt(server_fd, SOL_SOCKET, SO_REUSEADDR, &val, sizeof(val)) ==
        -1) {
        close(server_fd);
        throw std::runtime_error("Failed to configure server socket");
    }

    /*
     * struct sockaddr_in {
     *  uint16_t sin_family; // AF_INET
     *  uint16_t sin_port; // port in big-endian
     *  struct in_addr sin_addr; // IPv4
     * }
     *
     * struct in_addr {
     *  uint32_t s_addr; // IPv4 in big-endian
     * }
     */
    sockaddr_in address{};

    address.sin_family = AF_INET;
    address.sin_port =
        htons(port); // Converts port into big-endian for network byte order
    address.sin_addr.s_addr =
        htonl(INADDR_LOOPBACK); // htonl converts the address to big-endian
                                // (Host to Network Long)
                                // host is the CPU endian (small-endian)
                                // Network is the big-endian.
                                // INADDR_LOOPBACK defines the address 127.0.0.1

    if (bind(
            server_fd,
            (const sockaddr *)&address, // converts IPv4 address pointer into
                                        // older generic socket API pointer type
            sizeof(address)) == -1) {
        close(server_fd);
        throw std::runtime_error("Failed to bind server socket");
    }

    if (listen(server_fd, SOMAXCONN) == -1) {
        close(server_fd);
        throw std::runtime_error("Failed to listen on server socket!");
    }
    return server_fd;
}

struct Conn {
    int fd = -1;

    // app's intention, for the event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;

    // buffered input and output
    std::vector<uint8_t> incoming; // data to be parsed by the app
    std::vector<uint8_t> outgoing; // responses generated by the app
};

bool try_one_request(Conn *conn) {
    constexpr size_t header_size = 4;

    // Wait until we have complete header length
    if (conn->incoming.size() < header_size) {
        return false;
    }

    uint32_t len = 0;
    memcpy(&len, conn->incoming.data(), header_size);

    if (len > k_max_msg) {
        error_msg("Message too long\n");
        conn->want_close = true; // invalid
        return false;
    }

    const size_t frame_size = header_size + len;

    // We have the header, but maybe only part of the body
    if (conn->incoming.size() < frame_size) {
        return false;
    }

    // Echo the complete frame: length header followed by payload
    buf_append(conn->outgoing, conn->incoming.data(), frame_size);

    // Remove only the request we just processed
    buf_consume(conn->incoming, frame_size);

    return true;
}

void handle_read(Conn *conn) {
    uint8_t chunk[64 * 1024];

    ssize_t received = read(conn->fd, &chunk, sizeof(chunk));

    if (received < 0) {
        if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) {
            return;
        }

        conn->want_close = true;
        return;
    }

    if (received == 0) {
        // Peer has finished sending
        conn->want_close = true;
        return;
    }

    buf_append(conn->incoming, chunk, (size_t)received);

    while (try_one_request(conn)) {
        // TODO: do something for multiple messages
    }

    // there is data in the outgoing vector => need to write out
    if (!conn->want_close && !conn->outgoing.empty()) {
        conn->want_read = false;
        conn->want_write = true;
    }
}

void handle_write(Conn *conn) {
    // if there is nothing in outgoing array, we just set the connection to read
    if (conn->outgoing.empty()) {
        conn->want_read = true;
        conn->want_write = false;
        return;
    }

    ssize_t sent =
        write(conn->fd, conn->outgoing.data(), conn->outgoing.size());

    if (sent < 0) {
        if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) {
            return; // not error
        }

        conn->want_close = true;
        return;
    }

    if (sent == 0) {
        conn->want_close = true;
        return;
    }

    buf_consume(conn->outgoing, (size_t)sent);

    // if we have exhausted the outgoing array data, we set it to read
    if (conn->outgoing.empty()) {
        conn->want_read = true;
        conn->want_write = false;
    }
}

Conn *handle_accept(int server_fd) {
    struct sockaddr_in client_addr = {};
    socklen_t addrlen = sizeof(client_addr);
    int client_fd =
        accept(server_fd, (struct sockaddr *)&client_addr, &addrlen);

    if (client_fd < 0) {
        return NULL;
    }

    fd_set_nonblock(client_fd);

    // Create a new conn
    Conn *conn = new Conn();
    conn->fd = client_fd;
    conn->want_read = true;
    return conn;
}

// a map of all client connections, keyed by fd
std::vector<Conn *> fd2conn;

void run_server(int server_fd, int port) {
    printf("Listening on port %d\n", port);

    std::vector<pollfd> poll_args;

    while (true) {
        // Build this iteration's readiness requests
        poll_args.clear();

        // put the listening sockets in the first position
        struct pollfd pfd = {server_fd, POLLIN, 0};
        poll_args.push_back(pfd);

        for (Conn *conn : fd2conn) {
            if (conn == nullptr) {
                continue;
            }

            // always poll() for error
            struct pollfd pfd = {conn->fd, POLLERR, 0};

            // poll() flags from the application's intent
            if (conn->want_read) {
                pfd.events |= POLLIN;
            }

            if (conn->want_write) {
                pfd.events |= POLLOUT;
            }

            poll_args.push_back(pfd);
        }

        // wait for readiness
        int read_value = poll(poll_args.data(), (nfds_t)poll_args.size(), -1);
        if (read_value < 0 && errno == EINTR) {
            continue; // not an error
        }

        if (read_value < 0) {
            die("Poll");
        }

        // handle the listening socket
        if (poll_args[0].revents) {
            if (Conn *conn = handle_accept(server_fd)) {
                // put it into map
                if (fd2conn.size() <= (size_t)conn->fd) {
                    fd2conn.resize(conn->fd + 1);
                }

                assert(!fd2conn[conn->fd]);
                fd2conn[conn->fd] = conn;
            }
        }

        // handle connection sockets
        for (size_t i = 1; i < poll_args.size(); i++) { // skip first
            uint32_t ready = poll_args[i].revents;

            if (ready == 0) {
                continue;
            }

            Conn *conn = fd2conn[poll_args[i].fd];

            if (ready & POLLIN) {
                assert(conn->want_read);
                handle_read(conn);
            }

            if (ready & POLLOUT) {
                assert(conn->want_write);
                handle_write(conn);
            }

            // close the socket from socket error or application logic
            if ((ready & POLLERR) || conn->want_close) {
                (void)close(conn->fd);
                fd2conn[conn->fd] = NULL;
                delete conn;
            }
        }
    }
}

int main() {
    constexpr int port = 6379;
    int server_fd = -1;

    try {
        printf("MemVault is starting...\n");

        server_fd = create_server_socket(port);
        printf("Server socket successfully initialised and bound to port %d\n",
               port);
        fd_set_nonblock(server_fd);

        run_server(server_fd, port);
    } catch (const std::exception &error) {
        if (server_fd != -1) {
            close(server_fd);
        }
        fprintf(stderr, "Server error: %s\n", error.what());
        return 1;
    }

    close(server_fd);
    return 0;
}
